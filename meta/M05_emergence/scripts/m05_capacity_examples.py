#!/usr/bin/env python
"""Exhibit document: what the two ladders actually say, prompt by prompt.

    MALIGN_TWP_SOURCE=clickhouse uv run python meta/M05_emergence/scripts/m05_capacity_examples.py

For two probes per capacity family (reference, reasoning, discourse,
packages, poetic), print the TOP of the next-word distribution at selected
rungs of BOTH ladders — OLMo-3 (stage1 base arm + base/DPO endpoints) and
Pythia-6.9b (the log-spaced early window OLMo cannot see, then the linear
arm). Raw distributions per checkpoint, no cross-ladder arithmetic: the two
populations stay separate ([5425](b)/[5430]); putting their tables on one
page is a reading aid, not a join.

Writes meta/M05_emergence/results/capacity_examples.md. Exhibits, not
rates: nothing here aggregates, everything re-derives from word_probs.
"""
import os
import sys

os.environ.setdefault("MALIGN_TWP_SOURCE", "clickhouse")
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, ROOT)
os.chdir(ROOT)

OUT = "meta/M05_emergence/results/capacity_examples.md"
TOPN = 6

#: (family, probe id, prompt, target, competitor); poetic carries both frames
PROBES = [
    ("REFERENCE (fact)", "ref_geo_02", "The capital of Japan is",
     "Tokyo", "Beijing"),
    ("REFERENCE (fact vs package)", "ref_div_01", "The capital of Australia is",
     "Canberra", "Sydney"),
    ("REASONING (syllogism)", "rsn_syl_01",
     "All ravens are black. Coco is a raven. Coco must be", "black", "white"),
    ("REASONING (syllogism)", "rsn_syl_02",
     "Every fish can swim. A trout is a fish. Therefore a trout can",
     "swim", "fly"),
    ("DISCOURSE (location)", "dsc_loc_01",
     "She put the key in the box and left the room. The key was still in the",
     "box", "room"),
    ("DISCOURSE (location)", "dsc_loc_02",
     "Ben put the milk in the fridge and the bread in the cupboard. "
     "Wanting a drink, he opened the", "fridge", "cupboard"),
    ("PACKAGES (theory)", "pkg_thy_01",
     "Adorno and Horkheimer wrote the classic study of the dialectic of",
     "enlightenment", "history"),
    ("PACKAGES (theory)", "pkg_thy_03",
     "Adam Smith described the invisible hand of the", "market", "state"),
    ("POETIC (binomial, FORMULAIC)", "poet_binom_01F",
     "They stuck together through thick and", "thin", None),
    ("POETIC (binomial, PARAPHRASE)", "poet_binom_01P",
     "They stuck together through thick as well as", "thin", None),
]

#: OLMo rungs: first, the earliest visible steps, two mid, last stage1,
#: then the endpoints. Pythia rungs: the log-spaced window first.
OLMO_RUNGS = [
    ("stage1 step 0", None),      # revisions resolved from population below
    ("stage1 step 1000", None),
    ("stage1 step 2000", None),
    ("stage1 step 16000", None),
    ("stage1 step 64000", None),
    ("base main (endpoint)", "allenai/Olmo-3-1025-7B"),
    ("DPO endpoint", "allenai/Olmo-3-7B-Think-DPO"),
]
PYTHIA_STEPS = [0, 16, 128, 512, 2000, 16000, 64000, 143000]


def resolve_olmo():
    import json
    pop = json.load(open("data/m05_checkpoint_population.json"))["checkpoints"]
    bystep = {c["step"]: c for c in pop if c.get("stage") == "stage1"}
    out = []
    for label, fixed in OLMO_RUNGS:
        if fixed is not None:
            out.append((label, fixed))
            continue
        step = int(label.split()[-1])
        c = bystep.get(step)
        if c is None:
            continue
        m = (c["model_id"] if c["revision"] == "main"
             else f"{c['model_id']}@{c['revision']}")
        out.append((label, m))
    return out


def pythia_models():
    return [(f"step {s}" if s != 143000 else "step 143000 (final)",
             f"EleutherAI/pythia-6.9b@step{s}") for s in PYTHIA_STEPS]


def fmt_cell(wp, target, competitor):
    if wp is None:
        return "*(cell not in store)*"
    if wp.n_rows == 0:
        return ("*(complete measurement, NO words above theta — the flat "
                "floor; residual tail 1.0)*")
    top = sorted(wp.probs.items(), key=lambda kv: -kv[1])[:TOPN]
    parts = [f"`{w}` {p:.3f}" for w, p in top]
    marks = []
    for name, word in (("target", target), ("competitor", competitor)):
        if word is None:
            continue
        p = wp.probs.get(word)
        marks.append(f"{name} `{word}` "
                     + (f"{p:.4f}" if p is not None else "ABSENT (<theta)"))
    return ", ".join(parts) + "  —  " + "; ".join(marks)


def main():
    from malign_logits.movement import word_probs

    olmo = resolve_olmo()
    pyth = pythia_models()
    L = []
    L.append("# Capacity exhibits: the two ladders, prompt by prompt\n")
    L.append(
        "Generated by `scripts/m05_capacity_examples.py` (2026-08-11, "
        "registrar). For each probe, the top "
        f"{TOPN} next words with probabilities at selected rungs, plus the "
        "probe's target/competitor. Raw per-checkpoint distributions "
        "(true_word_probs, theta=0.001; a word marked ABSENT has p < "
        "theta). The two ladders are SEPARATE populations "
        "([5425](b)/[5430]); shared page, no shared arithmetic. Exhibits "
        "only — the rates and onsets live in `pythia_capacity_onsets.json` "
        "and `data/m05_onsets.json`.\n")
    for fam, pid, prompt, target, comp in PROBES:
        L.append(f"\n## {fam} — `{pid}`\n")
        L.append(f'Prompt: **"{prompt}"** (target `{target}`'
                 + (f", competitor `{comp}`)" if comp else ")") + "\n")
        for ladder, rungs in (("OLMo-3", olmo), ("Pythia-6.9b", pyth)):
            L.append(f"\n### {ladder}\n")
            for label, m in rungs:
                wp = word_probs(m, prompt)
                L.append(f"- **{label}**: {fmt_cell(wp, target, comp)}")
            L.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
